/** The titles, as the engine and the one-phone game draw them: by place in this list. */
export const TITLES: T[] = ALL.map(({ zh, en }) => ({ zh, en }));
/** Which pack each place in TITLES belongs to. */
export const TITLE_PACK: Pack[] = ALL.map((t) => t.pack);
/** The places in TITLES that the packs in play cover (none picked: every title). */
export function deckFor(packs: readonly string[]): number[] {
  const on = packs.filter(isPack);
  const places = TITLES.map((_, i) => i);
  return on.length ? places.filter((i) => on.includes(TITLE_PACK[i])) : places;
}
/** How many titles the packs in play hold. */
export const countFor = (packs: readonly string[]) => deckFor(packs).length;
