import type { T } from "../i18n";

export type Heat = 1 | 2;
/** `custom`: the card when the table plays for its own penalty instead of drinks. */
export type Prompt = T & { heat: Heat; custom?: T };

/*
 * Each card is written in both languages, the way people at a party would say it, not translated
 * word for word: a WeChat Moments post in Chinese can be a social post in English. A phone shows
 * one language, its own. Mild deals only mild cards and spicy only spicy ones (the wheel of fate
 * deals the mild ones too, so no mild card mentions drinking or the next person's pick). A dare
 * that touches someone else asks for someone willing (挑一个愿意的人). A time in a dare ("20 秒" /
 * "20 seconds") puts a countdown under it, so both languages name the same time
 * (tests/duration.test.ts), and no truth names one.
 */
const mild = (zh: string, en: string): Prompt => ({ zh, en, heat: 1 });
const spicy = (zh: string, en: string, custom?: T): Prompt => ({ zh, en, heat: 2, ...(custom ? { custom } : {}) });

/** A card in the words of the table's penalty: drinking, or the host's own. */
export function promptText(p: Prompt, custom: boolean): T {
  return custom && p.custom ? p.custom : { zh: p.zh, en: p.en };
}

