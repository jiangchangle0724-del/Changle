// Builds the game's fonts: only the characters the game actually uses, so they download fast.
//   node scripts/fonts.mjs      (re-run after adding new Chinese text; tests/fonts.test.ts will remind you)
// Sources: Google Fonts' GitHub repository, all five under the SIL Open Font License 1.1:
//   Unbounded and Figtree: the frame (headings, buttons, text), the same two fonts as the rest of
//     changle.ca. They have no Chinese: Chinese falls back to the phone's own font, as on the site.
//   ZCOOL QingKe HuangYou (站酷庆科黄油体): Chinese on the posters, the board and the stamps
//   Big Shoulders Display: English on the posters, the board and the stamps
//   Space Mono: numbers on tickets and stamps
// Output: src/client/fonts/*.woff2, fonts.css, chars.txt and the licences, all committed.
import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { join } from "node:path";
import subsetFont from "subset-font";

const RAW = "https://raw.githubusercontent.com/google/fonts/main/ofl/";
const CACHE = "node_modules/.cache/been-there-fonts";
const OUT = "src/client/fonts";

const FONTS = [
  { file: "unbounded.woff2", family: "Unbounded", weight: "600 800", src: "unbounded/Unbounded%5Bwght%5D.ttf", licence: "unbounded/OFL.txt", axes: { wght: { min: 600, max: 800 } } },
  // Text can be a player's name or a city's greeting, so it keeps the accented Latin letters too.
  { file: "figtree.woff2", family: "Figtree", weight: "400 800", src: "figtree/Figtree%5Bwght%5D.ttf", licence: "figtree/OFL.txt", axes: { wght: { min: 400, max: 800 } }, accents: true },
  { file: "zcool.woff2", family: "ZCOOL QingKe HuangYou", weight: 400, src: "zcoolqingkehuangyou/ZCOOLQingKeHuangYou-Regular.ttf", licence: "zcoolqingkehuangyou/OFL.txt", cjk: true },
  { file: "bigshoulders.woff2", family: "Big Shoulders Display", weight: 800, src: "bigshouldersdisplay/BigShouldersDisplay%5Bwght%5D.ttf", licence: "bigshouldersdisplay/OFL.txt", axes: { wght: 800 } },
  { file: "spacemono-400.woff2", family: "Space Mono", weight: 400, src: "spacemono/SpaceMono-Regular.ttf", licence: "spacemono/OFL.txt" },
  { file: "spacemono-700.woff2", family: "Space Mono", weight: 700, src: "spacemono/SpaceMono-Bold.ttf" },
];

async function fetchCached(path) {
  const local = join(CACHE, path.replace(/[/%]/g, "_"));
  if (existsSync(local)) return readFile(local);
  const res = await fetch(RAW + path);
  if (!res.ok) throw new Error(`download failed: ${path} (${res.status})`);
  const buf = Buffer.from(await res.arrayBuffer());
  await mkdir(CACHE, { recursive: true });
  await writeFile(local, buf);
  return buf;
}

async function walk(dir) {
  const out = [];
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) out.push(...(await walk(p)));
    else if (/\.(ts|tsx)$/.test(e.name)) out.push(p);
  }
  return out;
}

const sources = [...(await walk("src/client")), ...(await walk("src/local")), "src/engine/data.ts"];
const text = (await Promise.all(sources.map((f) => readFile(f, "utf8")))).join("");
const isCjk = (ch) => /[⺀-鿿　-〿＀-￯]/.test(ch);
const cjk = [...new Set([...text].filter(isCjk))].sort().join("");
const latin = Array.from({ length: 95 }, (_, i) => String.fromCharCode(32 + i)).join("") + "·—–‘’“”…→←×°";
// Latin-1 and Latin Extended-A (é, ñ, ü, ł, ş...), and the currency signs the cities use.
const accents = Array.from({ length: 0x180 - 0xa0 }, (_, i) => String.fromCharCode(0xa0 + i)).join("") + "€₩฿₺₹₽₱₫₪";

await mkdir(join(OUT, "licences"), { recursive: true });
let css = "/* Generated by scripts/fonts.mjs: subsets of five SIL OFL fonts (licences in ./licences). */\n";
for (const f of FONTS) {
  const font = await fetchCached(f.src);
  const chars = f.cjk ? cjk + latin + "，。、：；！？「」『』（）《》【】—…" : f.accents ? latin + accents : latin;
  const sub = await subsetFont(font, chars, { targetFormat: "woff2", ...(f.axes ? { variationAxes: f.axes } : {}) });
  await writeFile(join(OUT, f.file), sub);
  if (f.licence) await writeFile(join(OUT, "licences", `${f.family.replace(/\s+/g, "")}-OFL.txt`), await fetchCached(f.licence));
  css += `@font-face{font-family:"${f.family}";font-weight:${f.weight};font-style:normal;font-display:swap;src:url(fonts/${f.file}) format("woff2")}\n`;
  console.log(`${f.file}: ${(sub.length / 1024).toFixed(0)} KB`);
}
await writeFile(join(OUT, "fonts.css"), css);
await writeFile(join(OUT, "chars.txt"), cjk + "\n");
console.log(`${cjk.length} Chinese characters covered`);
