// Draws the world map used in the middle of the round board: Natural Earth 1:110m land (public domain,
// via the world-atlas package), seen from above the North Pole like the "air age" maps of the 1940s.
// Writes src/client/art/world.ts. Re-run with `node scripts/gen-world.mjs` (only needed if the look changes).
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { feature } from "topojson-client";

const require = createRequire(import.meta.url);
const topo = require("world-atlas/land-110m.json");

/** Southern edge of the map. Antarctica is left off, as on the old airline maps. */
const LAT_MIN = -58;
/** Map radius in output units; the client scales it to fit. */
const R = 1000;
/** Drop points closer than this to the last kept one (output units). */
const TOLERANCE = 5;

const project = ([lon, lat]) => {
  const r = ((90 - lat) / (90 - LAT_MIN)) * R;
  const a = (lon * Math.PI) / 180;
  // Longitude 0 points down, east runs anticlockwise: the globe seen from above the North Pole.
  return [r * Math.sin(a), r * Math.cos(a)];
};

const land = feature(topo, topo.objects.land);
const rings = [];
for (const f of land.features) {
  const polys = f.geometry.type === "Polygon" ? [f.geometry.coordinates] : f.geometry.coordinates;
  for (const poly of polys) {
    for (const ring of poly) {
      if (ring.every(([, lat]) => lat < LAT_MIN)) continue;
      const pts = [];
      for (const p of ring) {
        const [x, y] = project([p[0], Math.max(p[1], LAT_MIN)]);
        const last = pts[pts.length - 1];
        if (!last || Math.hypot(x - last[0], y - last[1]) >= TOLERANCE) pts.push([x, y]);
      }
      if (pts.length >= 4) rings.push(pts);
    }
  }
}

const d = rings.map((pts) => "M" + pts.map(([x, y]) => `${Math.round(x)} ${Math.round(y)}`).join("L") + "Z").join("");
const out = `// Generated by scripts/gen-world.mjs from Natural Earth 1:110m land (public domain, via world-atlas).
// North-polar azimuthal equidistant projection, radius ${R}, centre (0, 0), southern edge ${LAT_MIN}°.
export const WORLD_R = ${R};
export const WORLD_LAT_MIN = ${LAT_MIN};
export const LAND = ${JSON.stringify(d)};
`;
writeFileSync(new URL("../src/client/art/world.ts", import.meta.url), out);

// The same coastlines as plain longitude/latitude rings, coarser, for the low-poly globe sample (step 5).
const lonlat = [];
for (const f of land.features) {
  const polys = f.geometry.type === "Polygon" ? [f.geometry.coordinates] : f.geometry.coordinates;
  for (const poly of polys) {
    const ring = poly[0];
    const pts = [];
    for (const [lon, lat] of ring) {
      const last = pts[pts.length - 1];
      if (!last || Math.hypot(lon - last[0], lat - last[1]) >= 1.2) pts.push([Math.round(lon * 10) / 10, Math.round(lat * 10) / 10]);
    }
    if (pts.length >= 4) lonlat.push(pts);
  }
}
writeFileSync(new URL("../src/samples/land-lonlat.json", import.meta.url), JSON.stringify(lonlat));
console.log(`world.ts: ${rings.length} rings, ${rings.reduce((n, r) => n + r.length, 0)} points, ${(out.length / 1024).toFixed(1)} KB`);
