export type Key = keyof typeof S;

let lang: Lang = "zh";
export const setLang = (l: Lang) => {
  lang = l;
  document.documentElement.lang = l === "zh" ? "zh-CN" : "en";
};
export const getLang = () => lang;

/** A UI string with {placeholders} filled in. */
export function t(key: Key, vars: Record<string, string | number> = {}): string {
  const s = S[key]?.[lang === "zh" ? 0 : 1] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (k in vars ? String(vars[k]) : `{${k}}`));
}

/** The same string in the other language (for a bilingual title). */
export const other = (key: Key): string => S[key]?.[lang === "zh" ? 1 : 0] ?? key;

export const has = (key: string): key is Key => key in S;

/** Pick the current language from bilingual game data. */
export const tx = (text: Text) => text[lang];

/** "：" in Chinese, ": " in English. */
export const colon = () => (lang === "zh" ? "：" : ": ");

export const money = (n: number) => `$${Math.round(n).toLocaleString("en-US")}`;

export function spaceName(at: number): string {
  const sp = BOARD[at];
  switch (sp.k) {
    case "city":
      return tx(CITIES.find((c) => c.id === sp.id)!.name);
    case "route":
      return tx(ROUTES.find((r) => r.id === sp.id)!.name);
    case "service":
      return tx(SERVICES.find((r) => r.id === sp.id)!.name);
    case "tax":
      return t(sp.id === "departure" ? "tax_departure" : "tax_baggage");
    case "go":
      return t("departure");
    case "immigration":
      return t("immigration");
    case "lounge":
      return t("lounge");
    case "expired":
      return t("expired");
    case "journey":
      return t("journeySpace");
    case "postcard":
      return t("postcardSpace");
  }
}

export const groupName = (id: number) => tx(GROUPS.find((g) => g.id === id)!.name);

export function cardById(id: string) {
  return [...JOURNEY_CARDS, ...POSTCARDS].find((c) => c.id === id);
}

export const cardTitle = (id: string) => {
  const c = cardById(id);
  return c ? tx(c.title) : id;
};
