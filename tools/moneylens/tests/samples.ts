export const bytesOf = (text: string): Uint8Array => new TextEncoder().encode(text);

/** Text as Windows-1252 bytes (every character here is below U+0100, so one byte each). */
export const latin1 = (text: string): Uint8Array => Uint8Array.from(text, (c) => c.charCodeAt(0));

